import assert from "node:assert/strict";
import test from "node:test";
import { normalizeAdName, UNIDENTIFIED_NAME } from "./normalize";

test("tira o prefixo da conta em qualquer formato", () => {
  assert.equal(normalizeAdName("[HT7] - AD017-FB-ELEKTRA"), "AD017-FB-ELEKTRA");
  assert.equal(normalizeAdName("HT7 - AD017-FB-ELEKTRA"), "AD017-FB-ELEKTRA");
  assert.equal(normalizeAdName("HT7 | LT-RIFA-IPHONE-002"), "LT-RIFA-IPHONE-002");
  assert.equal(normalizeAdName("(HT7) LT-LF-CRESPO-001"), "LT-LF-CRESPO-001");
  assert.equal(normalizeAdName("{HT7} AD017-FB-ELEKTRA"), "AD017-FB-ELEKTRA");
  assert.equal(normalizeAdName('"HT7" - AD017-FB-ELEKTRA'), "AD017-FB-ELEKTRA");
  assert.equal(normalizeAdName("HT7 : LT-RIFA-IPHONE-002"), "LT-RIFA-IPHONE-002");
});

test("tira a tag da conta no fim e junta maiúsculas", () => {
  assert.equal(normalizeAdName("AD017-FB-ELEKTRA - HT7"), "AD017-FB-ELEKTRA");
  assert.equal(normalizeAdName("AD017-FB-ELEKTRA [HT7]"), "AD017-FB-ELEKTRA");
  assert.equal(normalizeAdName("lt-lf-crespo-001"), "LT-LF-CRESPO-001");
  assert.equal(normalizeAdName("LT-RIFA-IPHONE-002 - HT7"), "LT-RIFA-IPHONE-002");
});

test("mantém o nome espaçado que começa com LT e os sufixos V1 V2 V3", () => {
  assert.equal(normalizeAdName("LT - NOVELA - COPPEL - 001"), "LT-NOVELA-COPPEL-001");
  assert.equal(normalizeAdName("LT-IPHONE18-PERIODICO-AA-001-V1"), "LT-IPHONE18-PERIODICO-AA-001-V1");
  assert.equal(normalizeAdName("LT-IPHONE18-PERIODICO-AA-001-V2"), "LT-IPHONE18-PERIODICO-AA-001-V2");
  assert.equal(normalizeAdName("LT-IPHONE18-REPARTIDOR-AA-001-V3"), "LT-IPHONE18-REPARTIDOR-AA-001-V3");
  assert.notEqual(
    normalizeAdName("LT-IPHONE18-PERIODICO-AA-001-V1"),
    normalizeAdName("LT-IPHONE18-PERIODICO-AA-001-V2"),
  );
});

test("tira Copia e manda placeholder para o mesmo grupo", () => {
  assert.equal(
    normalizeAdName("LT-IPHONE18-PERIODICO-AA-001-V1 - Copia"),
    "LT-IPHONE18-PERIODICO-AA-001-V1",
  );
  assert.equal(normalizeAdName("AD017-FB-ELEKTRA - Copy"), "AD017-FB-ELEKTRA");
  assert.equal(normalizeAdName("AD017-FB-ELEKTRA (copia)"), "AD017-FB-ELEKTRA");
  assert.equal(normalizeAdName("{{ad.name}}"), UNIDENTIFIED_NAME);
  assert.equal(normalizeAdName('["HT7"]'), UNIDENTIFIED_NAME);
  assert.equal(normalizeAdName("   "), UNIDENTIFIED_NAME);
});

